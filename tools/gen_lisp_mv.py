#!/usr/bin/env python3
"""Generate core/lisp_eval_mv.mbt: for every ported function that returns
several values (a tuple in its MoonBit signature), a wrapper returning all
of them. The registry (core/gen_registry.mbt) installs these functions in
their function cells returning only the primary value; the Lisp evaluator
replaces those cells by wrappers that also set its values register, so
that MULTIPLE-VALUE-BIND & co. in interpreted code see every value.
Rerun after tools/gen.py."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

decls = open(os.path.join(ROOT, "core/gen_decls.mbt")).read()
arity = {}
for m in re.finditer(r"^declare fn (\w+)\((.*)\) -> \(([^()]*)\) raise", decls, re.M):
    arity[m.group(1)] = len([x for x in m.group(3).split(",") if x.strip()])

out = [
    "// GENERATED by tools/gen_lisp_mv.py from core/gen_registry.mbt.",
    "// Ported functions returning several values, as functions returning",
    "// all of them (see le__wrap_mv_functions).",
    "",
    "///|",
    "fn le__mv_wrappers() -> Array[(Value, (Array[Value]) -> Array[Value] raise)] {",
    "  [",
]
n = 0
reg = open(os.path.join(ROOT, "core/gen_registry.mbt")).read()
for m in re.finditer(r"^  defun\((q_\w+), args => ((\w+)\(.*\))\.0\)$", reg, re.M):
    sym, call, fname = m.group(1), m.group(2), m.group(3)
    k = arity.get(fname)
    if not k:
        continue
    elems = ", ".join("r.%d" % i for i in range(k))
    out.append("    (%s, args => {\n      let r = %s\n      [%s]\n    }),"
               % (sym, call, elems))
    n += 1
out += ["  ]", "}", ""]
open(os.path.join(ROOT, "core/lisp_eval_mv.mbt"), "w").write("\n".join(out))
print("multiple-valued functions", n)
