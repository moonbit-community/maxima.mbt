"""Generate core/gen_init.mbt: call implemented init_<file> in build order."""
import json, os, re, glob
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
import sys
sys.path.insert(0, HERE)
import gen
db = json.load(open(os.path.join(HERE, "db.json")))
excluded = set(open(os.path.join(HERE, "excluded.txt")).read().split())
src = ""
for f in glob.glob(os.path.join(ROOT, "core", "*.mbt")):
    if os.path.basename(f).startswith("gen_"):
        continue
    src += open(f).read()
defined = set(re.findall(r"^fn (init_[a-z0-9_]+)\(\)", src, re.M))
lines = ["// GENERATED by tools/gen_init.py -- do not edit.", "", "///|",
         "/// Initialize the whole system: variables, function cells, then each",
         "/// ported file's top-level forms in build order.",
         "fn init_generated() -> Unit raise {",
         "  init_generated_vars()",
         "  register_generated_functions()",
         "  register_generated_simplifiers()"]
# SBCL's real load order (from the reference build log: defsystem resolves
# :depends-on, so it differs from maxima.system's text order).
order_file = os.path.join(HERE, "load_order.txt")
rank = {}
if os.path.exists(order_file):
    for i, f in enumerate(open(order_file).read().split()):
        rank.setdefault(f, i)
core_files = [d for d in db if d["file"] not in excluded and d.get("module") != "share"]
core_files.sort(key=lambda d: rank.get(d["file"], 10 ** 6))
for d in core_files:
    nm = "init_" + gen.mangle(d["file"].split("/")[-1])
    if nm in defined and nm not in os.environ.get("SKIP_INIT", "").split(","):
        lines.append("  %s()" % nm)
# init functions of files outside the analyzed build list (e.g. numerical/
# quadpack.lisp), in a fixed order
known = set("init_" + gen.mangle(d["file"].split("/")[-1]) for d in db)
for nm in ["init_quadpack"]:
    if nm in defined and nm not in known:
        lines.append("  %s()" % nm)
lines.append("}")
# share Lisp packages: loaded on demand by load("<file>.lisp")
share = [d for d in db if d.get("module") == "share"]
src_vars = open(os.path.join(ROOT, "core", "gen_vars.mbt")).read()
for d in share:
    base = gen.mangle(d["file"].split("/")[-1])
    lines.append("")
    lines.append("///|")
    lines.append("fn share_load_%s() -> Unit raise {" % base)
    vfn = "init_vars_" + gen.mangle(d["file"].replace("/", "-"))
    if ("fn %s(" % vfn) in src_vars:
        lines.append("  %s()" % vfn)
    lines.append("  register_share_%s()" % base)
    if ("init_share_" + base) in defined:
        lines.append("  init_share_%s()" % base)
    lines.append("}")
lines.append("")
lines.append("///|")
lines.append("/// The ported share Lisp file named `stem` (file name without directory")
lines.append("/// and extension), if any.")
lines.append("fn share_module_loader(stem : String) -> (() -> Unit raise)? {")
lines.append("  match stem {")
for d in share:
    stem = d["file"].split("/")[-1]
    lines.append("    %s => Some(share_load_%s)" % (gen.moon_str(stem), gen.mangle(stem)))
lines.append("    _ => None")
lines.append("  }")
lines.append("}")
open(os.path.join(ROOT, "core", "gen_init.mbt"), "w").write("\n".join(lines) + "\n")
print("inits:", len(defined))
