#!/usr/bin/env python3
"""Generate core/lisp_eval_specials.mbt: the names of the globally special
variables of Maxima's Lisp code (DEFVAR, DEFPARAMETER, DEFCONSTANT, DEFMVAR,
DECLARE-TOP, DECLAIM/PROCLAIM SPECIAL at top level of every ported file),
which the Lisp evaluator binds dynamically. Local (declare (special ...))
forms do not make a variable globally special and are not included.
Rerun when files are added to the contract (tools/analyze.py)."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import analyze  # noqa: E402
from analyze import sym, read_file  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def specials_of(path):
    acc = set()

    def handle(f):
        if not isinstance(f, list) or not f:
            return
        h = sym(f[0])
        if h in ("progn", "eval-when"):
            for g in f[(2 if h == "eval-when" else 1):]:
                handle(g)
        elif h in ("defvar", "defparameter", "defconstant", "defmvar"):
            if len(f) > 1 and sym(f[1]):
                acc.add(sym(f[1]))
        elif h in ("declare-top", "declaim"):
            for d in f[1:]:
                if isinstance(d, list) and d and sym(d[0]) == "special":
                    for v in d[1:]:
                        if sym(v):
                            acc.add(sym(v))
        elif h == "proclaim" and len(f) > 1:
            q = f[1]
            if isinstance(q, analyze.Quote):
                q = q.form
            if isinstance(q, list) and q and sym(q[0]) == "special":
                for v in q[1:]:
                    if sym(v):
                        acc.add(sym(v))

    for f, _line in read_file(path):
        handle(f)
    return acc


def main():
    files = analyze.system_files()
    sf = os.path.join(os.path.dirname(__file__), "share_files.txt")
    if os.path.exists(sf):
        for line in open(sf).read().split():
            files.append(("share", "../" + line))
    names = set()
    for _module, rel in files:
        path = os.path.join(analyze.SRC, rel + ".lisp")
        try:
            names |= specials_of(path)
        except Exception as e:  # noqa: BLE001
            print("ERROR", rel, e, file=sys.stderr)
    names = sorted(n for n in names if "\n" not in n)
    out = [
        "// GENERATED by tools/gen_lisp_specials.py from the Maxima sources.",
        "// The globally special variables of Maxima's Lisp code: the Lisp",
        "// evaluator binds them dynamically.",
        "",
        "///|",
        "let le__maxima_specials_text : String =",
    ]
    for n in names:
        out.append("  #|" + n)
    out += [
        "",
        "///|",
        "let le__maxima_specials_set : Ref[Set[String]?] = Ref(None)",
        "",
        "///|",
        "fn le__maxima_specials() -> Set[String] {",
        "  match le__maxima_specials_set.val {",
        "    Some(s) => s",
        "    None => {",
        "      let s : Set[String] = Set::new()",
        "      for line in le__maxima_specials_text.split(\"\\n\") {",
        "        if line.length() > 0 {",
        "          s.add(line.to_string())",
        "        }",
        "      }",
        "      le__maxima_specials_set.val = Some(s)",
        "      s",
        "    }",
        "  }",
        "}",
        "",
    ]
    open(os.path.join(ROOT, "core/lisp_eval_specials.mbt"), "w").write("\n".join(out))
    print("specials", len(names))


if __name__ == "__main__":
    main()
