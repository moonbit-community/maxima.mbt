"""Generate core/gen_using.mbt importing every public lisp-runtime name."""
import re, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
mbti = open(os.path.join(ROOT, "lisp", "pkg.generated.mbti")).read()
vals, types = [], []
for line in mbti.splitlines():
    m = re.match(r"^pub (?:fn|let)(?:\[[^\]]*\])? ([a-z_][A-Za-z0-9_]*)\b", line)
    if m:
        vals.append(m.group(1))
        continue
    m = re.match(r"^pub(?:\(all\)|\(readonly\))? (?:struct|enum|type|suberror|typealias|trait) ([A-Z][A-Za-z0-9_]*)", line)
    if m:
        types.append(m.group(1))
vals = sorted(set(vals))
types = sorted(set(types))
out = ["// GENERATED by tools/gen_using.py -- do not edit.", "", "///|", "using @lisp {"]
for t in types:
    out.append("  type %s," % t)
for v in vals:
    out.append("  %s," % v)
out.append("}")
open(os.path.join(ROOT, "core", "gen_using.mbt"), "w").write("\n".join(out) + "\n")
open(os.path.join(HERE, "runtime_names.txt"), "w").write("\n".join(vals) + "\n")
print(len(vals), "values", len(types), "types")
