#!/usr/bin/env python3
"""Generate core/slatec_values.mbt: the Value-level SLATEC/QUADPACK routines
of the contract (`slatec_<name>` in core/gen_decls.mbt, one Value per Fortran
argument, returning the Lisp's multiple values) as adapters around the native
translations in the slatec/ package.

Usage: python3 tools/gen_slatec_values.py

The signatures come from tools/f2cl2mbt.py's analysis of the f2cl Lisp (the
same one that generates slatec/), so the adapters follow the f2cl calling
convention exactly:

* Scalar arguments must have the declared Lisp type (double-float,
  (signed-byte 32), logical, string; a TYPE-ERROR otherwise, as SBCL signals
  when binding the parameter). The one single-float parameter (INITDS's ETA)
  takes a Lisp float: the port has no single-floats.
* Array arguments must be Lisp vectors of the declared element type. They
  are copied to native arrays (an array passed for several parameters is
  copied once) and copied back after the call -- also when it raises -- so
  the caller sees the writes as with the Lisp's by-reference arrays. The
  native offset parameter of an array that internal callers pass as a
  section is 0: a Lisp vector passed here is always the whole array.
* Function arguments are Lisp function designators. QUADPACK's integrand F
  is called with a double and must return a double (the Lisp stores the
  value in a double-float variable in nearly every routine; a second value,
  which f2cl would store back into the argument, is ignored, as in the
  native translation). DASYJY's FUNJY
  (DJAIRY/DYAIRY) and DQK15W's W (DQWGTC/F/S) are called with all their
  arguments; FUNJY's non-NIL values replace the corresponding arguments,
  W's value is the weight. The native code does not let those two raise,
  so an error inside them is kept and raised when the routine returns.
* The result has one value per values slot of the Lisp (the function value
  first for a FUNCTION subprogram); slots the Lisp returns as NIL are NIL.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import f2cl2mbt as F  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECLS = os.path.join(ROOT, "core", "gen_decls.mbt")
OUT = os.path.join(ROOT, "core", "slatec_values.mbt")

LISP_TYPE = {"D": "DOUBLE-FLOAT", "I": "(SIGNED-BYTE 32)", "F": "SINGLE-FLOAT",
             "B": "(MEMBER T NIL)", "S": "SIMPLE-STRING"}
CONV_IN = {"D": "slv__d", "I": "slv__i", "F": "slv__f", "B": "slv__b", "S": "slv__s"}


def conv_out(t, code):
    return {"D": "Flo(%s)", "I": "Fix(%s.to_int64())", "F": "Flo(%s.to_double())",
            "B": "lbool(%s)", "S": "Str(%s)"}[t] % code


def contract():
    """lisp name -> (moonbit name, [param names], number of values)."""
    out = {}
    lines = open(DECLS).read().split("\n")
    for i, l in enumerate(lines):
        m = re.match(r"/// defun slatec::(\S+) -- ", l)
        if not m:
            continue
        j = i + 1
        while not lines[j].startswith("declare fn"):
            j += 1
        d = re.match(r"declare fn (\w+)\((.*)\) -> (.*) raise$", lines[j])
        params = [p.split(" : ")[0] for p in d.group(2).split(", ")] if d.group(2) else []
        ret = d.group(3)
        n = ret.count("Value")
        out[m.group(1)] = (d.group(1), params, n)
    return out


PRELUDE = r'''// GENERATED by tools/gen_slatec_values.py -- do not edit; regenerate with
//   python3 tools/gen_slatec_values.py
//
// The Value-level SLATEC/QUADPACK routines of the contract
// (numerical/slatec/*.lisp): adapters following the f2cl calling convention
// around the native translations in the slatec/ package (see
// docs/SLATEC.md and the generator's docstring).

///|
fn slv__type_error(x : Value, ty : String, param : String) -> Error {
  LispError::Condition(
    intern("type-error"),
    "The value \{prin1_to_string(x)} is not of type \{ty} when binding SLATEC::\{param}",
    x,
  )
}

///|
fn slv__d(x : Value, param : String) -> Double raise {
  match x {
    Flo(d) => d
    _ => raise slv__type_error(x, "DOUBLE-FLOAT", param)
  }
}

///|
fn slv__i(x : Value, param : String) -> Int raise {
  match x {
    Fix(n) if n >= -2147483648L && n <= 2147483647L => n.to_int()
    _ => raise slv__type_error(x, "(SIGNED-BYTE 32)", param)
  }
}

///|
/// A single-float parameter: the port has no single-floats, so any Lisp
/// float is accepted and rounded.
fn slv__f(x : Value, param : String) -> Float raise {
  match x {
    Flo(d) => Float::from_double(d)
    _ => raise slv__type_error(x, "SINGLE-FLOAT", param)
  }
}

///|
fn slv__b(x : Value, param : String) -> Bool raise {
  match x {
    Nil => false
    _ if eq(x, t) => true
    _ => raise slv__type_error(x, "(MEMBER T NIL)", param)
  }
}

///|
fn slv__s(x : Value, param : String) -> String raise {
  match x {
    Str(s) => s
    Vec(a) if a.elt == "character" => lstring(x)
    _ => raise slv__type_error(x, "SIMPLE-STRING", param)
  }
}

///|
/// The Lisp arrays of one call and their native copies.
priv struct SlvArrays {
  ds : Array[(LArray, FixedArray[Double])]
  is_ : Array[(LArray, FixedArray[Int])]
}

///|
fn SlvArrays::new() -> SlvArrays {
  { ds: [], is_: [] }
}

///|
/// The native copy of a Lisp (vector double-float).
fn SlvArrays::d(self : SlvArrays, x : Value, param : String) -> FixedArray[Double] raise {
  match x {
    Vec(a) if a.elt == "double-float" && a.dims.length() == 1 => {
      for p in self.ds {
        if physical_equal(p.0, a) {
          return p.1
        }
      }
      let fa : FixedArray[Double] = FixedArray::make(a.data.length(), 0.0)
      for i, v in a.data {
        fa[i] = match v {
          Flo(d) => d
          _ => raise slv__type_error(x, "(VECTOR DOUBLE-FLOAT)", param)
        }
      }
      self.ds.push((a, fa))
      fa
    }
    _ => raise slv__type_error(x, "(VECTOR DOUBLE-FLOAT)", param)
  }
}

///|
/// The native copy of a Lisp (vector (signed-byte 32)).
fn SlvArrays::i(self : SlvArrays, x : Value, param : String) -> FixedArray[Int] raise {
  match x {
    Vec(a) if (a.elt == "fixnum" || a.elt == "integer") && a.dims.length() == 1 => {
      for p in self.is_ {
        if physical_equal(p.0, a) {
          return p.1
        }
      }
      let fa : FixedArray[Int] = FixedArray::make(a.data.length(), 0)
      for i, v in a.data {
        fa[i] = match v {
          Fix(n) if n >= -2147483648L && n <= 2147483647L => n.to_int()
          _ => raise slv__type_error(x, "(VECTOR (SIGNED-BYTE 32))", param)
        }
      }
      self.is_.push((a, fa))
      fa
    }
    _ => raise slv__type_error(x, "(VECTOR (SIGNED-BYTE 32))", param)
  }
}

///|
/// Copy the native arrays back into the Lisp arrays.
fn SlvArrays::back(self : SlvArrays) -> Unit {
  for p in self.ds {
    for i in 0..<p.1.length() {
      p.0.data[i] = Flo(p.1[i])
    }
  }
  for p in self.is_ {
    for i in 0..<p.1.length() {
      p.0.data[i] = Fix(p.1[i].to_int64())
    }
  }
}

///|
/// A QUADPACK integrand: (funcall f x), which must be a double-float.
fn slv__integrand(f : Value) -> (Double) -> Double raise {
  x => {
    let r = le__funcall(f, [Flo(x)])
    le__mv.val = None
    match r {
      Flo(d) => d
      _ => raise type_error(r, "DOUBLE-FLOAT")
    }
  }
}

///|
/// All the values of (funcall f args...).
fn slv__call_values(f : Value, args : Array[Value]) -> Array[Value] raise {
  le__mv.val = None
  let v = le__funcall(f, args)
  le__values_of(v)
}

///|
/// Value K of a function argument's values, as f2cl's
/// (when var-k (setf <arg> var-k)) uses it: NIL keeps the argument.
fn slv__slot_d(vs : Array[Value], k : Int, arg : Double) -> Double raise {
  if k >= vs.length() {
    return arg
  }
  match vs[k] {
    Nil => arg
    Flo(d) => d
    v => raise type_error(v, "DOUBLE-FLOAT")
  }
}

///|
/// The primary value of a function argument returning a weight (DQK15W's
/// W): the Lisp multiplies it by the double-float integrand value, so any
/// real number is accepted (with float contagion).
fn slv__value_d(vs : Array[Value]) -> Double raise {
  let v = if vs.length() == 0 { Value::Nil } else { vs[0] }
  match v {
    Flo(d) => d
    _ if realp(v) => to_double(v)
    _ => raise type_error(v, "REAL")
  }
}
'''


def mb_t(t):
    return F.mbt_type(t)


def gen_closure(fd, p, var, sig, bindings, lines):
    """A native closure for the non-raising function parameter P (bound to
    VAR): errors are kept in <var>_err and raised after the call."""
    gs = bindings.get((fd.name, p), set())
    is_fn = all(F.FNS[g].is_function for g in gs) and gs
    args = ["a%d" % k for k in range(len(sig.args))]
    params = ", ".join("%s : %s" % (a, mb_t(t)) for a, t in zip(args, sig.args))
    vals = []
    for a, t in zip(args, sig.args):
        if t == "D":
            vals.append("Flo(%s)" % a)
        elif t == "I":
            vals.append("Fix(%s.to_int64())" % a)
        else:
            raise SystemExit("closure arg type %r in %s.%s" % (t, fd.name, p))
    slot_ts = [t for _, t in sig.slots]
    if any(t != "D" for t in slot_ts):
        raise SystemExit("closure result type in %s.%s" % (fd.name, p))
    if is_fn:
        if [k for k, _ in sig.slots] != [0]:
            raise SystemExit("closure slots in %s.%s" % (fd.name, p))
        body = "slv__value_d(vs)"
        dflt = "0.0"
    else:
        # subroutine: values slot k is argument k
        parts = ["slv__slot_d(vs, %d, a%d)" % (k, k) for k, _ in sig.slots]
        dflt_parts = ["a%d" % k for k, _ in sig.slots]
        body = parts[0] if len(parts) == 1 else "(" + ", ".join(parts) + ")"
        dflt = dflt_parts[0] if len(parts) == 1 else "(" + ", ".join(dflt_parts) + ")"
    ret = F.ret_type(slot_ts)
    lines.append("  let %s_err : Ref[Error?] = Ref(None)" % var)
    lines.append("  let %s_fn = fn(%s) -> %s {" % (var, params, ret))
    lines.append("    if %s_err.val is Some(_) {" % var)
    lines.append("      return %s" % dflt)
    lines.append("    }")
    lines.append("    let vs = slv__call_values(%s, [%s]) catch {" % (var, ", ".join(vals)))
    lines.append("      e => {")
    lines.append("        %s_err.val = Some(e)" % var)
    lines.append("        return %s" % dflt)
    lines.append("      }")
    lines.append("    }")
    lines.append("    %s catch {" % body)
    lines.append("      e => {")
    lines.append("        %s_err.val = Some(e)" % var)
    lines.append("        %s" % dflt)
    lines.append("      }")
    lines.append("    }")
    lines.append("  }")


def gen_adapter(fd, mbname, pnames, nret, bindings):
    if len(pnames) != len(fd.params):
        raise SystemExit("arity mismatch for %s" % fd.name)
    nvals = len(fd.values)
    if max(nvals, 1) != nret:
        raise SystemExit("values mismatch for %s: %d vs %d" % (fd.name, nvals, nret))
    ret = "Value" if nret == 1 else "(" + ", ".join(["Value"] * nret) + ")"
    sig = ", ".join("%s : Value" % p for p in pnames)
    lines = ["///|", "/// " + ("FUNCTION" if fd.is_function else "SUBROUTINE") +
             " slatec::%s (numerical/slatec/%s.lisp)" % (fd.name, fd.file or "xerror"),
             "fn %s(%s) -> %s raise {" % (mbname, sig, ret)]
    has_arrays = any(F.is_array_type(fd.ptypes[p]) for p in fd.params)
    if has_arrays:
        lines.append("  let arrs = SlvArrays::new()")
    after = []
    args = []
    for p, v in zip(fd.params, pnames):
        t = fd.ptypes[p]
        pl = p.upper()
        if isinstance(t, tuple) and t[0] == "A":
            if t[1] == "D":
                args.append('arrs.d(%s, "%s")' % (v, pl))
            elif t[1] == "I":
                args.append('arrs.i(%s, "%s")' % (v, pl))
            else:
                raise SystemExit("array type %r" % (t,))
            if fd.needs_off.get(p):
                args.append("0")
        elif isinstance(t, tuple) and t[0] == "FN":
            s = t[1]
            if s.key() == F.USER_FN.key():
                args.append("slv__integrand(%s)" % v)
            elif not s.raises:
                gen_closure(fd, p, v, s, bindings, lines)
                args.append("%s_fn" % v)
                after.append(v)
            else:
                raise SystemExit("raising closure %s.%s" % (fd.name, p))
        elif t in CONV_IN:
            args.append('%s(%s, "%s")' % (CONV_IN[t], v, pl))
        else:
            raise SystemExit("param type %r in %s" % (t, fd.name))
    if has_arrays:
        lines.append("  defer arrs.back()")
    call = "@slatec.%s(%s)" % (F.mb_fn_name(fd.name), ", ".join(args))
    slots = fd.slots()
    if not slots:
        lines.append("  %s" % call)
    else:
        lines.append("  let r = %s" % call)
    for v in after:
        lines.append("  if %s_err.val is Some(e) {" % v)
        lines.append("    raise e")
        lines.append("  }")
    out = ["Nil"] * max(nvals, 1)
    for k, (i, t) in enumerate(slots):
        code = "r" if len(slots) == 1 else "r.%d" % k
        if isinstance(t, tuple):
            raise SystemExit("array slot in %s" % fd.name)
        out[i] = conv_out(t, code)
    if nvals == 0:
        # (values): no values at all
        lines.append("  le__values([])")
    elif nret == 1:
        lines.append("  %s" % out[0])
    else:
        lines.append("  (%s)" % ", ".join(out))
    lines.append("}")
    return "\n".join(lines)


def main():
    F.LIB = F.lib_config("slatec")
    F.analyze()
    bindings = F.fn_bindings()
    decls = contract()
    parts = [PRELUDE]
    for name in sorted(decls):
        if name not in F.FNS:
            raise SystemExit("no native routine for slatec::%s" % name)
        mbname, pnames, nret = decls[name]
        parts.append(gen_adapter(F.FNS[name], mbname, pnames, nret, bindings))
    with open(OUT, "w") as f:
        f.write("\n\n".join(parts) + "\n")
    print("wrote %s (%d routines)" % (os.path.relpath(OUT, ROOT), len(decls)), file=sys.stderr)


if __name__ == "__main__":
    main()
