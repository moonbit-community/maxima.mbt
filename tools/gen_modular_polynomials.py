"""Generate core/share_modular_polynomials_data.mbt from
share/contrib/elliptic_curves/modular_polynomials.lisp: the (setf (svref
*ec-g* l) '(...)) data of the Mueller and Atkin modular polynomials, with
#x hex integers converted to decimal so that the runtime reader (lread)
can parse them."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
repos = os.environ.get("MAXIMA_REPOS", os.path.join(ROOT, ".repos"))
src = os.path.join(repos, "maxima/share/contrib/elliptic_curves/modular_polynomials.lisp")
text = open(src).read()
# drop #| ... |# block comments and ; line comments
text = re.sub(r"#\|.*?\|#", "", text, flags=re.S)
text = re.sub(r";[^\n]*", "", text)


def tokens(s):
    i, n = 0, len(s)
    while i < n:
        c = s[i]
        if c.isspace():
            i += 1
        elif c in "()'":
            yield c
            i += 1
        else:
            j = i
            while j < n and not s[j].isspace() and s[j] not in "()'":
                j += 1
            yield s[i:j]
            i = j


def conv(tok):
    m = re.fullmatch(r"#[xX]([+-]?)([0-9a-fA-F]+)", tok)
    if m:
        return str(int(m.group(1) + m.group(2), 16))
    assert re.fullmatch(r"[+-]?[0-9]+|[()]", tok), tok
    return tok


toks = list(tokens(text))
entries = []
i = 0
while i < len(toks):
    if (toks[i] == "(" and i + 3 < len(toks) and toks[i + 1] == "svref"
            and toks[i + 2] in ("*ec-g*", "*ec-g1*")):
        which = 0 if toks[i + 2] == "*ec-g*" else 1
        l = int(toks[i + 3])
        assert toks[i + 4] == ")"
        i += 5
        if toks[i] == "nil":
            entries.append((which, l, "nil"))
            i += 1
            continue
        assert toks[i] == "'" and toks[i + 1] == "("
        i += 1
        depth = 0
        out = []
        while True:
            t = toks[i]
            if t == "(":
                depth += 1
            elif t == ")":
                depth -= 1
            out.append(conv(t))
            i += 1
            if depth == 0:
                break
        s = " ".join(out).replace("( ", "(").replace(" )", ")")
        entries.append((which, l, s))
    else:
        i += 1

lines = [
    "// GENERATED by tools/gen_modular_polynomials.py from",
    "// share/contrib/elliptic_curves/modular_polynomials.lisp -- do not edit.",
    "//",
    "// Modular polynomials for p <= 151: the coefficients were copied from",
    "// PARI/GP (license GPL). PARI/GP extracted the polynomials from the",
    "// ECHIDNA databases (http://echidna.maths.usyd.edu.au/kohel/dbs/); they",
    "// were computed by David R. Kohel, University of Sydney.",
    "//",
    "// Each entry: (0 for *ec-g* / 1 for *ec-g1*, l, Lisp text of the value).",
    "",
    "///|",
    "let share_modular_polynomials__data : Array[(Int, Int, String)] = [",
]
for which, l, s in entries:
    lines.append("  (%d, %d, \"%s\")," % (which, l, s))
lines.append("]")
out = os.path.join(ROOT, "core", "share_modular_polynomials_data.mbt")
open(out, "w").write("\n".join(lines) + "\n")
print(len(entries), "entries")
